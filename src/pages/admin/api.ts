// Admin data layer: every call goes through the signed-in admin client, so what succeeds is decided by
// the RLS policies in supabase_schema.sql (public.is_admin()). Errors are plain `Error`s with a readable message.

import { getAdminSupabase, type PropertyRow } from '@/lib/supabase';

export const STATUSES = ['disponible', 'reservado', 'vendido', 'alquilado'] as const;
export type Status = (typeof STATUSES)[number];

/** Fields the form writes. `slug` is deliberately absent: the DB trigger generates it and edits never change it. */
export interface PropertyInput {
  title: string;
  operation: 'venta' | 'alquiler';
  property_type: string;
  status: Status;
  price: number;
  currency: 'USD' | 'ARS';
  neighborhood: string;
  city: string;
  address: string | null;
  location: string;
  bedrooms: number;
  bathrooms: number;
  covered_area: number | null;
  total_area: number;
  parking: number;
  description: string;
  images: string[];
  features: string[];
  featured: boolean;
  badge: string | null;
}

const fail = (message: string): never => { throw new Error(message); };

export async function fetchAllProperties(): Promise<PropertyRow[]> {
  const sb = await getAdminSupabase();
  const { data, error } = await sb.from('properties').select('*').order('created_at', { ascending: false });
  if (error) fail(error.message);
  return data as PropertyRow[];
}

/** Insert (id = null) or update. `slug` is generated by the database on insert and kept on update. */
export async function saveProperty(id: string | null, input: PropertyInput): Promise<PropertyRow> {
  const sb = await getAdminSupabase();
  const q = id ? sb.from('properties').update(input).eq('id', id) : sb.from('properties').insert(input);
  const { data, error } = await q.select().single();
  if (error) fail(error.code === '23505' ? 'Ya existe una propiedad con ese enlace (slug).' : error.message);
  return data as PropertyRow;
}

export async function setPropertyStatus(id: string, status: Status): Promise<void> {
  const sb = await getAdminSupabase();
  const { data, error } = await sb.from('properties').update({ status }).eq('id', id).select('id');
  if (error) fail(error.message);
  if (!data?.length) fail('No se pudo actualizar (¿tu usuario es admin?).');
}

export async function deleteProperty(id: string): Promise<void> {
  const sb = await getAdminSupabase();
  const { data, error } = await sb.from('properties').delete().eq('id', id).select('id');
  if (error) fail(error.message);
  if (!data?.length) fail('No se pudo eliminar (¿tu usuario es admin?).');
}

// ── Photos (Supabase Storage bucket `property-images`, public read; writes restricted to admins by RLS) ──
export const IMAGE_BUCKET = 'property-images';
export const MAX_IMAGE_BYTES = 10 * 1024 * 1024;
const IMAGE_EXT: Record<string, string> = { 'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp' };

/** Uploads one JPG / PNG / WEBP to the bucket and returns its public URL. */
export async function uploadPropertyImage(file: File): Promise<string> {
  const ext = IMAGE_EXT[file.type];
  if (!ext) fail(`"${file.name}": solo se aceptan JPG, PNG o WEBP.`);
  if (file.size > MAX_IMAGE_BYTES) fail(`"${file.name}" supera los 10 MB.`);
  const sb = await getAdminSupabase();
  const path = `${crypto.randomUUID()}.${ext}`;
  const { error } = await sb.storage.from(IMAGE_BUCKET).upload(path, file, { contentType: file.type, cacheControl: '31536000' });
  if (error) fail(`No se pudo subir "${file.name}": ${error.message}`);
  return sb.storage.from(IMAGE_BUCKET).getPublicUrl(path).data.publicUrl;
}

// ── Contact requests (public.contacts: visitors insert, only admins read / manage) ──
export const CONTACT_STATUSES = ['nuevo', 'leido', 'respondido', 'archivado'] as const;
export type ContactStatus = (typeof CONTACT_STATUSES)[number];

export interface ContactRow {
  id: string;
  created_at: string;
  name: string;
  email: string;
  phone: string | null;
  message: string;
  property_id: string | null;
  status: ContactStatus;
  /** Joined listing (null for general requests or if the listing was deleted). */
  properties: { title: string; slug: string } | null;
}

export async function fetchContacts(): Promise<ContactRow[]> {
  const sb = await getAdminSupabase();
  const { data, error } = await sb.from('contacts').select('*, properties(title, slug)').order('created_at', { ascending: false });
  if (error) fail(error.message);
  return data as unknown as ContactRow[];
}

export async function setContactStatus(id: string, status: ContactStatus): Promise<void> {
  const sb = await getAdminSupabase();
  const { data, error } = await sb.from('contacts').update({ status }).eq('id', id).select('id');
  if (error) fail(error.message);
  if (!data?.length) fail('No se pudo actualizar (¿tu usuario es admin?).');
}

export async function deleteContact(id: string): Promise<void> {
  const sb = await getAdminSupabase();
  const { data, error } = await sb.from('contacts').delete().eq('id', id).select('id');
  if (error) fail(error.message);
  if (!data?.length) fail('No se pudo eliminar (¿tu usuario es admin?).');
}
